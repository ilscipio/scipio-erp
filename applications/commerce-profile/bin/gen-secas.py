"""Generates servicedef/secas.xml from the lists below. Run from the repository root:
   python applications/commerce-profile/bin/gen-secas.py
Checks each name against the service definitions of the source tree and prints the names that it does not find."""
import os, re, sys

# CMS services that take a template body, a script or a template location (they write code)
CMS_CODE = """cmsCreatePageTemplate cmsAddPageTemplateVersion cmsUpdatePageTemplateScript cmsUpdatePageScript
cmsUpdateAssetTemplateScript cmsCreateUpdateScriptTemplate cmsCreateUpdateAsset cmsImportXmlData""".split()
# CMS services that return code (need CMS_CODE_VIEW)
CMS_VIEW = "cmsGetScriptTemplate cmsGetPageTemplateVersion cmsExportDataAsXml cmsExportDataAsXmlInline".split()

CODE = """importEntityFileDirectory entityImportDir entityImportReaders importDelimitedEntityFile parseEntityXmlFile
entityExportAll getEntityExport deleteEntityExport exportEntityEoModelBundle exportServiceEoModelBundle saveLabelsToXmlFile
exportAllAlternativeUrlsEntityXml exportAlternativeUrlsEntityXmlFileFromConfig exportWebsiteAlternativeUrlsEntityXmlFile
loadOfflineEntitySyncData storeEntitySyncData pullAndReportEntitySyncData remotePullAndReportEntitySyncDataHttp
remotePullAndReportEntitySyncDataRmi remoteStoreEntitySyncDataHttp remoteStoreEntitySyncDataRmi
createJobSandbox updateJobSandbox deleteJobSandbox cancelScheduledJob resetScheduledJob purgeOldJobs cancelJobRetries
createRuntimeData updateRuntimeData deleteRuntimeData createJobManagerLock updateJobManagerLock
createSequenceValueItem updateSequenceValueItem deleteSequenceValueItem
testGroovy testGroovyMethod testBsh testJavaScript testScriptEngineBsh testScriptEngineGroovy testScriptEngineGroovyMethod
testScriptEngineJavaScript testScriptEngineJavaScriptFunction testHttp testSoap testSoapSimple testRemoteSoap testRemoteSoap1
testRemoteSoap2 testRemoteSoap3 testRemoteSoap4 testRoute testJMSQueue testJMSTopic
createFile updateFile startFileListener triggerFileEvent ftpGetFile ftpPutFile generateMySqlFileWithAlterTableForTimestamps
demoDataGenerator createApplicationSandbox updateApplicationSandbox deleteApplicationSandbox cmsDemoReset""".split()

IMPORT = ["entityImport"]
SCREEN_FILE = ["createFileFromScreen"]

def known_services(root):
    names = set()
    for base in ("applications", "framework", "addons"):
        for d, _, fs in os.walk(os.path.join(root, base)):
            if os.sep + "build" in d or os.sep + "runtime" in d:
                continue
            for f in fs:
                p = os.path.join(d, f)
                if f.endswith(".java"):
                    t = open(p, encoding="utf-8", errors="ignore").read()
                    names.update(re.findall(r'@Service\(\s*name\s*=\s*"(\w+)"', t))
                elif f.endswith(".xml") and "servicedef" in d:
                    t = open(p, encoding="utf-8", errors="ignore").read()
                    names.update(re.findall(r'<service name="(\w+)"', t))
    return names

def main():
    root = os.getcwd()
    known = known_services(root)
    mail = sorted(n for n in known if n.startswith("sendMail") and not n.endswith("Interface"))
    groups = [("hostedGuardCmsCode", "CMS services that take a template body, a script or a location (CMS_CODE_UPDATE)", CMS_CODE),
              ("hostedGuardCmsView", "CMS services that return code (CMS_CODE_VIEW)", CMS_VIEW),
              ("hostedGuardCode", "Code, data load, jobs and file services (operators and system only)", CODE),
              ("hostedGuardImport", "entityImport: only the files of hosted.import.allow", IMPORT),
              ("hostedGuardMail", "Mail: no mail server choice from a store caller", mail),
              ("hostedGuardScreenFile", "createFileFromScreen: no path, plain file name, component screen", SCREEN_FILE)]
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<!-- SCIPIO: 4.0.0: Hosted profile (W1-02). GENERATED by bin/gen-secas.py: change the lists there, not this file.',
           '     Each rule runs a guard service at event auth: the first ECA event, before the login check and before every other ECA of the service.',
           '     A guard error stops the service and its later ECA events (a rule on the same event still runs: no other rule on these services uses auth).',
           '     A guard refuses only when scipio.hosted=true. See docs/wp/W1-02.md. -->',
           '<service-eca xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
           '        xsi:noNamespaceSchemaLocation="http://ofbiz.apache.org/dtds/service-eca.xsd">']
    missing = []
    for guard, title, names in groups:
        out.append('')
        out.append('    <!-- %s -->' % title)
        for n in names:
            if n not in known:
                missing.append(n)
                continue
            out.append('    <eca service="%s" event="auth">' % n)
            out.append('        <action service="%s" mode="sync" ignore-error="false" ignore-failure="false"/>' % guard)
            out.append('    </eca>')
    out.append('</service-eca>')
    dest = os.path.join(root, "applications", "commerce-profile", "servicedef", "secas.xml")
    open(dest, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("wrote", dest, "rules:", sum(1 for l in out if "<eca " in l))
    if missing:
        print("ERROR: not a service in the source tree:", " ".join(missing), file=sys.stderr)
        sys.exit(1)

main()
